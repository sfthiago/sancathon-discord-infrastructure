function buildTeamChannels(team, index) {
  const number = String(team.number).padStart(2, "0");
  const keyPrefix = `team${number}`;
  const overwrite = () => ({
    target: team.roleKey,
    allow: ["ViewChannel"],
    deny: [],
  });

  return [
    {
      key: `${keyPrefix}Text`,
      name: `equipe-${number}`,
      aliases: [],
      type: "GuildText",
      categoryKey: "teams",
      order: index * 2,
      teamKey: team.roleKey,
      overwrites: [overwrite()],
    },
    {
      key: `${keyPrefix}Voice`,
      name: `equipe-${number}`,
      aliases: [],
      type: "GuildVoice",
      categoryKey: "teams",
      order: index * 2 + 1,
      teamKey: team.roleKey,
      overwrites: [overwrite()],
    },
  ];
}

const teamChannels = serverConfig.teams.flatMap(buildTeamChannels);

